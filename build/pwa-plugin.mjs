import {createHash} from 'node:crypto';
import {readdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';

const CACHE_PREFIX='dook-offline-';
const PRECACHE_EXCLUDED=new Set(['art/movement-reference.png','robots.txt','sitemap.xml']);

async function outputFiles(directory,prefix=''){
 const files=[];
 for(const entry of await readdir(directory,{withFileTypes:true})){
  if(entry.name.startsWith('.'))continue;
  const relative=prefix+entry.name;
  if(entry.isDirectory())files.push(...await outputFiles(path.join(directory,entry.name),relative+'/'));
  else if(entry.isFile()&&relative!=='sw.js'&&!relative.endsWith('.map')&&!PRECACHE_EXCLUDED.has(relative)&&!relative.startsWith('social/'))files.push(relative);
 }
 return files.sort();
}

// Keep the complete precached release immutable: a new online HTML response can
// reference a newer build, while offline navigation must retain a matching shell
// and chunks until that build has successfully installed its own worker.
export function renderServiceWorker(files,version){
 return `/* Generated by the Dook production build. Do not edit. */
const CACHE_PREFIX=${JSON.stringify(CACHE_PREFIX)};
const CACHE_NAME=CACHE_PREFIX+${JSON.stringify(version)};
const PRECACHE=${JSON.stringify(files.map(file=>'/'+file))};
const PRECACHE_PATHS=new Set(PRECACHE);

self.addEventListener('install',event=>{
 event.waitUntil((async()=>{
  const cache=await caches.open(CACHE_NAME);
  try{
   // addAll rejects the entire installation if even one required file fails.
   await cache.addAll(PRECACHE.map(url=>new Request(url,{cache:'reload'})));
  }catch(error){
   await caches.delete(CACHE_NAME);
   throw error;
  }
 })());
 // Deliberately wait for existing game tabs to close before adopting an update.
});

self.addEventListener('activate',event=>{
 event.waitUntil((async()=>{
  const names=await caches.keys();
  await Promise.all(names.filter(name=>name.startsWith(CACHE_PREFIX)&&name!==CACHE_NAME).map(name=>caches.delete(name)));
  // First installation can control this load without reloading a running game.
  await self.clients.claim();
 })());
});

function shellPath(pathname){
 if(pathname==='/'||pathname==='/index.html')return '/index.html';
 if(pathname==='/character-lab.html')return '/character-lab.html';
 return PRECACHE_PATHS.has(pathname)&&pathname.endsWith('.html')?pathname:null;
}

async function navigate(request,url){
 const controller=new AbortController();
 const timeout=setTimeout(()=>controller.abort(),4500);
 let response;
 try{
  response=await fetch(request,{signal:controller.signal,cache:'no-store'});
  if(response.ok)return response;
 }catch{}
 finally{clearTimeout(timeout);}
 const shell=shellPath(url.pathname);
 if(shell){
  const cached=await (await caches.open(CACHE_NAME)).match(shell);
  if(cached)return cached;
 }
 return response||new Response('This page is unavailable offline. Open Dook, Dook, Goose! from its home screen icon.',{status:503,headers:{'Content-Type':'text/plain; charset=utf-8'}});
}

async function asset(request,url){
 const cache=await caches.open(CACHE_NAME);
 const cached=await cache.match(url.pathname);
 if(cached)return cached;
 const response=await fetch(request);
 if(response.ok&&response.type==='basic'){
  // A storage failure must not discard an otherwise usable online response.
  try{await cache.put(url.pathname,response.clone());}catch{}
 }
 return response;
}

self.addEventListener('fetch',event=>{
 const request=event.request;
 if(request.method!=='GET')return;
 const url=new URL(request.url);
 if(url.origin!==self.location.origin)return;
 if(request.mode==='navigate'){
  event.respondWith(navigate(request,url));
  return;
 }
 // Only shipped static files and Vite's hashed chunks belong in this cache.
 // Dev modules, API responses and third-party requests pass straight through.
 const hashedAsset=url.pathname.startsWith('/assets/')&&/-[A-Za-z0-9_-]{8,}\\.[a-z0-9]+$/i.test(url.pathname);
 if((PRECACHE_PATHS.has(url.pathname)&&!url.pathname.endsWith('.html'))||hashedAsset){
  if(request.headers.has('range'))return;
  event.respondWith(asset(request,url));
 }
});
`;
}

export default function dookPwa(){
 let config;
 return {
  name:'dook-production-offline',
  apply:'build',
  configResolved(resolved){
   config=resolved;
   if(!config.build.ssr&&config.base!=='/')throw new Error('Dook offline installation requires root hosting (Vite base: /).');
  },
  writeBundle:{
   order:'post',
   sequential:true,
   async handler(options){
    if(config.build.ssr||config.isWorker)return;
    const directory=path.resolve(config.root,options.dir||config.build.outDir);
    // Vite has copied public/ before Rollup writes output, so this includes both
    // generated chunks and fonts, live character textures, and app icons. Social
    // previews, crawler files, and unused movement study art stay network-only.
    const files=await outputFiles(directory);
    const manifest=JSON.parse(await readFile(path.join(directory,'manifest.webmanifest'),'utf8'));
    const required=['index.html','character-lab.html','manifest.webmanifest',...manifest.icons.map(icon=>icon.src.replace(/^\//,''))];
    for(const file of required)if(!files.includes(file))throw new Error('Cannot prepare offline Dook: missing '+file);
    const hash=createHash('sha256').update(renderServiceWorker.toString());
    for(const file of files){hash.update('\0'+file+'\0');hash.update(await readFile(path.join(directory,file)));}
    const version=hash.digest('hex').slice(0,16);
    await writeFile(path.join(directory,'sw.js'),renderServiceWorker(files,version));
    config.logger.info('Dook offline: '+files.length+' files precached, release '+version+'.');
   }
  }
 };
}
